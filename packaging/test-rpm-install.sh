#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IMAGE="${IMAGE:-fedora:latest}"
VERSION="$(python3 -c 'import tomllib; print(tomllib.load(open("'"$ROOT"'/backend/Cargo.toml", "rb"))["workspace"]["package"]["version"])')"
WORK="$(mktemp -d)"

cleanup() {
    docker run --rm -v "$WORK:/work" "$IMAGE" \
        chown -R "$(stat -c '%u:%g' "$WORK")" /work >/dev/null 2>&1 || true
    rm -rf "$WORK"
}
trap cleanup EXIT

command -v docker >/dev/null 2>&1 || {
    echo "docker is required" >&2
    exit 1
}

TOPDIR="$WORK/rpmbuild"
SOURCES="$TOPDIR/SOURCES"
mkdir -p "$SOURCES/dnsapi" "$TOPDIR/BUILD" "$TOPDIR/BUILDROOT" \
    "$TOPDIR/RPMS" "$TOPDIR/SPECS" "$TOPDIR/SRPMS"

for binary in angie-panel apctl; do
    printf '#!/bin/sh\nexit 0\n' > "$SOURCES/$binary"
done
cp "$ROOT/LICENSE" "$SOURCES/"
cp "$ROOT/packaging/angie-panel.toml" "$SOURCES/"
cp "$ROOT"/packaging/systemd/*.service "$SOURCES/"
cp "$ROOT/packaging/polkit/10-angie-panel.rules" "$SOURCES/"
cp "$ROOT/packaging/tmpfiles/angie-panel.conf" "$SOURCES/"
cp "$ROOT"/packaging/snippets/{block-exploits,cache-assets}.conf "$SOURCES/"
cp "$ROOT/backend/data/geoip-countries.csv" "$SOURCES/"

# These are generated by the release build; placeholders are sufficient to
# exercise the RPM payload and install scriptlets.
printf 'RPM install-test fixture\n' > "$SOURCES/VENDOR.txt"
printf '#!/bin/sh\nexit 0\n' > "$SOURCES/acme.sh"
printf '#!/bin/sh\nexit 0\n' > "$SOURCES/dnsapi/dns_test.sh"
for asset in angie-panel.1 apctl.1 apctl.bash angie-panel.bash _apctl _angie-panel apctl.fish; do
    printf 'RPM install-test fixture\n' > "$SOURCES/$asset"
done

sed "s/@VERSION@/$VERSION/g" "$ROOT/packaging/rpm/angie-panel.spec.in" \
    > "$TOPDIR/SPECS/angie-panel.spec"

docker image inspect "$IMAGE" >/dev/null 2>&1 || docker pull -q "$IMAGE" >/dev/null
if ! docker run --rm -e PACKAGE_VERSION="$VERSION" -v "$WORK:/work" "$IMAGE" bash -euc '
    dnf install -y rpm-build shadow-utils systemd dbus polkit curl
    cat > /work/angie.spec <<'"'"'SPEC'"'"'
Name:           angie
Version:        1.12
Release:        1
Summary:        RPM install-test dependency fixture
License:        MIT
BuildArch:      noarch

%description
Test-only provider for the Angie package dependency.

%install
mkdir -p %{buildroot}%{_datadir}/angie-test
touch %{buildroot}%{_datadir}/angie-test/provider

%files
%{_datadir}/angie-test/provider
SPEC
    mkdir -p /work/fake/{BUILD,BUILDROOT,RPMS,SOURCES,SPECS,SRPMS}
    rpmbuild --define "_topdir /work/fake" -bb /work/angie.spec
    rpmbuild --define "_topdir /work/rpmbuild" -bb /work/rpmbuild/SPECS/angie-panel.spec
    dnf install -y --setopt=install_weak_deps=False \
        /work/fake/RPMS/noarch/angie-1.12-1.noarch.rpm \
        /work/rpmbuild/RPMS/*/angie-panel-*.rpm
    test "$(rpm -q angie-panel --qf "%{VERSION}")" = "$PACKAGE_VERSION"
    test -x /usr/bin/angie-panel
    test -x /usr/bin/apctl
    test -f /etc/angie-panel.toml
    test -f /usr/lib/systemd/system/angie-panel.service
    test -f /usr/share/angie-panel/snippets/block-exploits.conf
    getent passwd angie-panel >/dev/null
    test "$(stat -c "%a" /var/lib/angie-panel)" = 700
' > "$WORK/container.log" 2>&1; then
    cat "$WORK/container.log" >&2
    exit 1
fi

printf 'RPM install test passed (Fedora, version %s)\n' "$VERSION"
